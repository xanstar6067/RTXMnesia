using System;
using System.Collections.Generic;
using UnityEngine;

namespace RTXMnesia.Hpl
{
    /// <summary>
    /// The game texts of one language (cLanguageFile, LanguageFile.cpp): categories of named entries, already
    /// decoded ([uNNNN] → character, [br] → line break). Entries of the first loaded file win, like HPL2
    /// (config/lang_main/&lt;lang&gt;.lang, then config/base_&lt;lang&gt;.lang, then English for missing ones).
    /// Also lists the sound files of the language folder (lang/rus/voices/...) with their durations, so voice
    /// lines can be timed before the sound system exists.
    /// Generated by the importer into Assets/AmnesiaImported/Lang (game data, never in git).
    /// </summary>
    public class HplLanguage : ScriptableObject
    {
        [Serializable]
        public class Entry
        {
            public string name;
            [TextArea] public string text;
        }

        [Serializable]
        public class Category
        {
            public string name;
            public List<Entry> entries = new();
        }

        [Serializable]
        public struct Voice
        {
            [Tooltip("File name without extension, lower case.")]
            public string name;
            [Tooltip("Path relative to the game folder.")]
            public string file;
            public float duration;
        }

        public string language;
        public string campaignId = "main";
        public List<string> sourceFiles = new();
        [Tooltip("RESOURCES folders of the language (fonts/rus, lang/rus): searched first for its fonts and voices.")]
        public List<string> resourceDirs = new();
        public List<Category> categories = new();
        public List<Voice> voices = new();

        Dictionary<string, Dictionary<string, string>> _lookup;
        Dictionary<string, Voice> _voices;

        /// <summary>kTranslate: the text, or "" (with a warning) when the category or entry is missing.</summary>
        public string Translate(string category, string entry)
        {
            if (TryTranslate(category, entry, out string text)) return text;
            Debug.LogWarning($"[RTXMnesia] Could not find language entry '{category}' / '{entry}'");
            return "";
        }

        public bool TryTranslate(string category, string entry, out string text)
        {
            text = "";
            if (_lookup == null) BuildLookup();
            return _lookup.TryGetValue(category ?? "", out var entries) && entries.TryGetValue(entry ?? "", out text);
        }

        /// <summary>A sound of the language folder by file name (extension optional, any case).</summary>
        public bool TryGetVoice(string file, out Voice voice)
        {
            if (_voices == null)
            {
                _voices = new Dictionary<string, Voice>(StringComparer.OrdinalIgnoreCase);
                foreach (var v in voices) _voices.TryAdd(v.name, v);
            }
            string name = System.IO.Path.GetFileNameWithoutExtension(file ?? "");
            return _voices.TryGetValue(name, out voice);
        }

        void BuildLookup()
        {
            _lookup = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
            foreach (var c in categories)
            {
                if (!_lookup.TryGetValue(c.name, out var entries)) _lookup[c.name] = entries = new Dictionary<string, string>(StringComparer.Ordinal);
                foreach (var e in c.entries) entries.TryAdd(e.name, e.text);
            }
        }

        void OnValidate()
        {
            _lookup = null;
            _voices = null;
        }
    }
}
