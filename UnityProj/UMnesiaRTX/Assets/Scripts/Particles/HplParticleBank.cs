using System;
using System.Collections.Generic;
using UnityEngine;

namespace RTXMnesia.Particles
{
    public enum PEStartPosType { Box, Sphere }
    public enum PEGravityType { None, Vector, Center }
    public enum PESubDivType { Random, Animation }
    public enum PEPartSpinType { Constant, Movement }
    /// <summary>eParticleEmitterType that a .ps can ask for ("point" is the dynamic point).</summary>
    public enum PEDrawType { Point, Line, Axis }
    public enum PECoordSystem { World, Local }

    /// <summary>
    /// The game's particle systems (.ps, cParticleSystemData): every file of particles/ with its emitters, found by
    /// name like cParticleManager::CreatePS (FileSearcher). Generated by ParticleConverter into
    /// Assets/AmnesiaImported/Particles (game data, never in git).
    /// </summary>
    public class HplParticleBank : ScriptableObject
    {
        [Serializable]
        public class SystemData
        {
            [Tooltip("File name without extension, lower case.")]
            public string name;
            [Tooltip("Path relative to the game folder, lower case, without extension.")]
            public string path;
            public List<EmitterData> emitters = new();
        }

        /// <summary>
        /// cParticleEmitterData_UserData::LoadFromElement: the values of one &lt;ParticleEmitter&gt;, in HPL2 space and
        /// units (angles in radians). Beam emitters (PEType="Beam") are not drawn by HPL2 either.
        /// </summary>
        [Serializable]
        public class EmitterData
        {
            public string name;
            public bool beam;
            public int maxParticleNum = 1;
            public bool respawn;
            public float particlesPerSecond = 1f, startTimeOffset;
            public float warmUpTime, warmUpStepsPerSec = 60f;
            public float minPauseLength, maxPauseLength, minPauseInterval, maxPauseInterval;
            public Vector3 posOffset, angleOffset;

            [Header("Material")]
            [Tooltip("The material frames (MaterialNum > 1: name01, name02, ...), RTXMnesia/HplParticle.")]
            public Material[] materials = Array.Empty<Material>();
            public float frameStep, maxFrameTime;
            public Vector2Int subDiv = Vector2Int.one;
            public PESubDivType subDivType;

            [Header("Start position")]
            public PEStartPosType startPosType;
            public Vector3 minStartPos, maxStartPos;
            public Vector2 minStartAngles, maxStartAngles;
            public float minStartRadius, maxStartRadius;

            [Header("Movement")]
            public PEStartPosType startVelType;
            public Vector3 minStartVel, maxStartVel;
            public Vector2 minStartVelAngles, maxStartVelAngles;
            public float minStartVelSpeed, maxStartVelSpeed;
            public float minSpeedMultiply, maxSpeedMultiply;
            public Vector3 minStartAcc, maxStartAcc;
            public float minVelMaximum, maxVelMaximum;
            public bool usesDirection;
            public PEGravityType gravityType;
            public Vector3 gravityAcc;
            public PECoordSystem coordSystem;
            public bool usePartSpin;
            public PEPartSpinType partSpinType;
            public float minSpinRange, maxSpinRange;
            public bool useRevolution;
            public Vector3 minRevVel, maxRevVel;

            [Header("Life")]
            public float minLifeSpan, maxLifeSpan;

            [Header("Rendering")]
            public PEDrawType drawType;
            public Vector2 minStartSize = Vector2.one, maxStartSize = Vector2.one;
            public float startRelSize, middleRelSize, middleRelSizeTime, middleRelSizeLength, endRelSize;
            public bool multiplyRGBWithAlpha;

            [Header("Color")]
            public Color minStartColor = Color.white, maxStartColor = Color.white;
            public Color startRelColor = Color.white, middleRelColor = Color.white, endRelColor = Color.white;
            public float middleRelColorTime, middleRelColorLength;

            [Header("Collision")]
            public bool collides;
            public float minBounceAmount, maxBounceAmount;
            public int minCollisionMax, maxCollisionMax;
            public int collisionUpdateRate;
        }

        public List<SystemData> systems = new();

        Hpl.HplNameIndex<SystemData> _index;

        /// <summary>cParticleManager::CreatePS: a .ps by name (extension optional, folders choose).</summary>
        public SystemData Get(string file)
        {
            if (_index == null)
            {
                _index = new Hpl.HplNameIndex<SystemData>();
                foreach (var s in systems) _index.Add(s.name, s.path, s);
            }
            return _index.Find(file);
        }
    }
}
